// Builds dist/n8n-cleanup-snippet.js from src/cleanup.js for an n8n Code node
// in "Run Once for Each Item" mode (JavaScript).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export function buildSnippet() {
  // Line endings are normalized so a CRLF checkout on Windows builds the same snippet.
  const source = readFileSync(new URL("../src/cleanup.js", import.meta.url), "utf8").replace(/\r\n/g, "\n");
  const functions = source.replace(/^export /gm, "").trim();

  return `// Generated by scripts/build-n8n-code.mjs from src/cleanup.js. Do not edit by hand.
// n8n Code node, mode "Run Once for Each Item".
// If the item has an "ai_text" field (raw AI answer), it runs cleanAiOutput and keeps the other fields.
// Otherwise it runs normalizeInput on the item.
// Output always has "ok". On failure it also has "error" and "stage" for the Dead Letter row.

${functions}

const item = $input.item.json;
if (typeof item.ai_text === "string") {
  return { json: { ...item, ...cleanAiOutput(item.ai_text) } };
}
return { json: normalizeInput(item) };
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const snippet = buildSnippet();
  const outDir = new URL("../dist/", import.meta.url);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(new URL("n8n-cleanup-snippet.js", outDir), snippet);
  process.stdout.write(`Wrote dist/n8n-cleanup-snippet.js (${snippet.length} characters)\n`);
}
