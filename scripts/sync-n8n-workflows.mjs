// Copies the shared contract into n8n/lead-inbox.workflow.json:
// - every Code node whose code starts with the generated header gets the current cleanup snippet
// - the "Config" Set node gets the current prompt texts from prompts/
// Run after changing src/cleanup.js or prompts/*.md. test/n8n-workflows.test.js fails on drift.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildSnippet } from "./build-n8n-code.mjs";

export const WORKFLOW_FILE = new URL("../n8n/lead-inbox.workflow.json", import.meta.url);
export const SNIPPET_HEADER = "// Generated by scripts/build-n8n-code.mjs";

// Returns the first ```text block under "## <heading>" in a prompt file.
export function readPromptBlock(promptFile, heading) {
  const markdown = readFileSync(new URL(`../prompts/${promptFile}`, import.meta.url), "utf8").replace(/\r\n/g, "\n");
  const section = markdown.split(`\n## ${heading}\n`)[1];
  const block = section?.match(/```text\n([\s\S]*?)\n```/);
  if (!block) throw new Error(`No text block under "## ${heading}" in prompts/${promptFile}`);
  return block[1];
}

export function expectedPrompts() {
  return {
    classify_system: readPromptBlock("classify.md", "System prompt"),
    classify_user: readPromptBlock("classify.md", "User template"),
    repair_system: readPromptBlock("repair.md", "System prompt"),
    repair_user: readPromptBlock("repair.md", "User template"),
  };
}

export function syncWorkflow(workflow) {
  const snippet = buildSnippet();
  const prompts = expectedPrompts();
  for (const node of workflow.nodes) {
    if (node.type === "n8n-nodes-base.code" && node.parameters.jsCode?.startsWith(SNIPPET_HEADER)) {
      node.parameters.jsCode = snippet;
    }
    if (node.name === "Config") {
      for (const assignment of node.parameters.assignments.assignments) {
        if (assignment.name in prompts) assignment.value = prompts[assignment.name];
      }
    }
  }
  return workflow;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const workflow = syncWorkflow(JSON.parse(readFileSync(WORKFLOW_FILE, "utf8")));
  writeFileSync(WORKFLOW_FILE, `${JSON.stringify(workflow, null, 2)}\n`);
  process.stdout.write("Synced n8n/lead-inbox.workflow.json with src/cleanup.js and prompts/\n");
}
